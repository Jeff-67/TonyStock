"""Module containing prompt generation functions for financial analysis agents."""


def get_knowledge_update_prompt(
    current_knowledge: str,
    new_content: str,
    company_name: str | None = None,
) -> str:
    """Generate prompt for knowledge update."""
    return f"""You are an investment analyst maintaining our company knowledge base for information searching strategy. Review the new report and update our company background knowledge.

Current instruction:
```
{current_knowledge if current_knowledge else "No existing knowledge"}
```

New Content:
```
{new_content}
```

Knowledge Management Guidelines:

─────────────────────────────

【背景說明】
請先整理目標公司或產業的歷史背景與最新動態，涵蓋財務數據、營運狀況、技術創新、業務拓展、供應鏈布局、外部環境、政策動向及市場反饋等。根據以下各部分邏輯與推理，生成一份針對【{company_name}】的「深度搜索與分析指南」，要求信息涵蓋更廣、思考更深、推理更全面，且支持建立從微觀技術到宏觀行業及政策環境的完整因果鏈。

【第一部分：基本面、歷史背景與核心定位】
1. 公司/產業歷史與發展脈絡
   - 描述成立年份、創業背景、關鍵轉型節點（例如：從傳統產業轉向高科技、從區域市場向全球市場擴展等）。
   - 突顯核心產品、服務或技術，以及公司在產業中所佔的獨特位置。
   - 推理：例如，分析早期技術積累如何轉變為現有的競爭優勢。
   - 範例查詢："`公司名稱` 歷史發展", "`公司名稱` 核心技術 演進"

2. 關鍵財務與經營指標
   - 詳列EPS、毛利率、營業利率、ROE、現金流、本益比等數據，說明公司盈利狀況與成長潛力。
   - 分析歷年業績表現與趨勢，探討數據背後的戰略調整與市場變化。
   - 推理：例如，如何從財務數據看出企業風險控制及資源配置效率。
   - 範例查詢："`公司名稱` 財務分析", "`公司名稱` 本益比 趨勢 分析"

【第二部分：業務拓展、策略與新市場佈局】
1. 傳統業務與核心客戶關係
   - 描述公司現有主要客戶的合作模式、依賴度及穩定性。
   - 分析這一合作關係的優勢與風險，並推導出替代策略必要性。
   - 範例查詢："`公司名稱` AMAT 合作 深度", "`公司名稱` 主要客戶 分析"

2. 新市場開拓與多角化策略
   - 探討公司如何突破單一客戶依賴，向其他新領域擴展業務。
   - 分析新興市場（如電動車零組件、航太、AI應用等）的機遇與挑戰，並思考產品與技術如何匹配市場需求。
   - 推理：結合行業成長數據與公司技術優勢，評估新市場的收益預期與風險分散效應。
   - 範例查詢："`公司名稱` ASML 新訂單", "`公司名稱` 電動車 零件 拓展", "`公司名稱` 航太 市場 進入"

【第三部分：技術創新、研發能力與產品推廣】
1. 研發投入與技術突破
   - 說明公司在技術研發、產品創新、自動化升級上的具體投入與成果，特別關注新產品（如EUV製程零件、先進封裝應用）如何形成突破。
   - 推理：探討技術創新如何轉化為市場競爭優勢，並帶動後續訂單、產品更新與客戶認同。
   - 範例查詢："`公司名稱` 技術創新 最新", "`公司名稱` EUV 零件 技術突破", "`公司名稱` 自動化 研發 成果"

2. 差異化戰略與品質保證
   - 分析公司與同業（例如`競爭對手`）在產品質量、製造效率、技術壁壘上的對比，並探討品牌與市場認知如何促進訂單轉化。
   - 推理：優化的品質管理如何降低生產風險並提高客戶信任度。
   - 範例查詢："`公司名稱` 品質管理 數據對比", "`公司名稱` 技術優勢 同業比較"

【第四部分：供應鏈整合、全球布局與外部環境】
1. 全球供應鏈與風險分散
   - 詳述公司在全球範圍內的佈局（如矽谷研發中心、泰國新廠等），探討如何應對美中科技戰、地緣政治變化等外部風險。
   - 推理：全球供應鏈的多元配置如何提升抵禦市場波動的能力，並減少區域性風險；從中推導出公司未來成長的可持續性。
   - 範例查詢："`公司名稱` 全球布局 戰略", "`公司名稱` 供應鏈 風險 應對"

2. 行業及宏觀經濟驅動因素
   - 探索產業整體趨勢、資本支出、技術進步（如先進製程需求、GAA技術落地）以及宏觀經濟環境對公司的潛在影響。
   - 推理：結合政策變化、行業指標等，評估外部驅動因素如何塑造未來市場格局並影響公司業績。
   - 範例查詢："`產業類型` 市場 趨勢 分析", "先進製程 設備 資本支出 趨勢", "宏觀經濟 `產業類型` 影響"

【第五部分：競爭環境、同行分析與轉型邏輯】
1. 主要競爭對手與市場競爭格局
   - 確定主要競爭對手，對比市場份額、技術創新、產品差異與財務指標，探討各自的優勢與劣勢。
   - 推理：從競爭對手的動態可以推導出整體市場競爭態勢及目標公司的相對位置。
   - 範例查詢："`公司名稱` 同業比較", "`公司名稱` vs `競爭對手` 市佔率", "`公司名稱` 市場定位 分析"

2. 轉型策略與供應商關係深化
   - 分析公司如何從供應鏈邊緣轉向核心供應商角色，提升與主要客戶（例如AMAT）的合作等級，並通過新技術和產品推動市場轉變。
   - 推理：深入探討轉型成功的標誌及其對未來業績和市場地位的長期影響。
   - 範例查詢："`公司名稱` 轉型 案例", "`公司名稱` 與主要客戶 深化合作", "`公司名稱` 市佔率 提升 路徑"

【第六部分：綜合查詢策略與信息時效性規劃】
1. 組合關鍵詞策略
   - 設計具體的關鍵詞組合，根據不同信息更新頻率進行分類：
     ◦ 即時資訊：如 "`公司名稱` 當日 新訂單", "`公司名稱` 股價 快訊", "`公司名稱` 當前 新聞"
     ◦ 近期資訊（7日內）：如 "`公司名稱` 最新財報", "`公司名稱` 新合作 宣佈", "`公司名稱` 訂單 更新"
     ◦ 中長期動態：如 "`公司名稱` 新廠 量產 計劃", "`公司名稱` 技術創新 市場推廣", "`公司名稱` 未來 發展 戰略"

2. 多角度交叉驗證與因果鏈構建
   - 鼓勵同時從技術、業務、供應鏈、政策、競爭與市場反饋等多個角度進行關鍵詞交叉查詢，形成完整邏輯鏈條。
   - 例如：先查詢 "`公司名稱` 技術突破"，再關注 "`公司名稱` 新產品 市場反應"，最終追蹤 "`公司名稱` 業績 改善" 的直接關聯與因果效應。

【第七部分：戰略風險、未來展望與政策影響】
1. 風險因素與潛在挑戰
   - 分析公司可能面臨的技術、財務、外部市場、政策與地緣政治等方面的風險。
   - 推理：考慮全球經濟、政策變動、行業調整對公司未來發展的可能不利影響，並提出監測重點。
   - 範例查詢："`公司名稱` 風險 分析", "`公司名稱` 政策 影響 評估", "`公司名稱` 地緣政治 風險"

2. 未來發展預測與場景分析
   - 探討公司在不同市場、技術與政策環境下的未來路徑，構建多種可能發展場景（例如保守、激進、平穩發展）。
   - 推理：結合內部轉型與外部行業趨勢，預測未來市場地位及其對投資價值的長遠影響。
   - 範例查詢："`公司名稱` 未來 發展 預測", "`公司名稱` 場景 分析", "`公司名稱` 轉型 成果 評估"

【生成要求與說明】
請依據以上所有部分內容，生成一份針對【{company_name}】的「深度搜索與分析指南」，要求：
   □ 詳盡介紹公司歷史、定位與核心競爭力
   □ 分析關鍵財務數據、業績趨勢與投資價值
   □ 說明傳統市場與新興業務的拓展策略及具體查詢示例
   □ 評估技術創新、產品研發與自動化升級成果，以及與同業的差異化優勢
   □ 解讀全球供應鏈、外部環境（包括地緣政治與政策調整）及行業趨勢
   □ 進行同行競爭和市場份額的對比分析，並探究轉型邏輯
   □ 包含多層次查詢的具體關鍵詞及時效性分類（即時、近期、中長期）
   □ 建立從技術研發→市場反饋→業績改善→投資價值提升的完整因果推導鏈條
   □ 融入戰略風險、未來展望與政策影響等深層思考，幫助全面捕捉與公司相關的所有信息

─────────────────────────────
【使用指南】
1. 將模板中的 `公司名稱`、`產業類型`、`競爭對手` 等變數替換為目標公司的實際名稱與描述。
2. 根據最新資料與歷史背景，動態補充具體數據與案例，保持信息的時效性與充分性。
3. 利用但不侷限於模板中的查詢示例，設計多角度組合式查詢方案，形成信息交叉驗證的因果鏈。
4. 以上框架提供參考，請依據各個公司狀況進行動態調整，目標是最終生成的指南應具備足夠深度及廣度，能驅動搜索 agent 捕捉從技術突破到市場反饋、從內部轉型到外部政策環境的全方位信息，滿足不同產業和公司的分析需求。

─────────────────────────────
Response format:
a json format with the key "updated_instruction" and the value is the updated instruction.
"""


def finance_agent_prompt(stock_id: str | None = None) -> str:
    """Generate finance agent prompt for stock analysis.

    Creates a specialized prompt for analyzing financial information and news
    related to a specific stock identified by its ID. The prompt includes
    guidance for comprehensive market analysis and news evaluation.

    Args:
        stock_id: The stock identifier to analyze

    Returns:
        Formatted prompt string for the finance agent
    """
    if not stock_id:
        return ""
    with open(
        f"prompts/company_knowledge/{stock_id}_background.md", "r", encoding="utf-8"
    ) as file:
        instruction = file.read()
    return instruction
